// GymOS — Service Worker (network-first)
// Quando sei online prende SEMPRE la versione più fresca dei file dell'app;
// la cache serve solo da fallback offline. Le chiamate al Worker Notion
// (altra origine) NON passano da qui.
const CACHE = "gymos-v1";

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));

self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin) return; // lascia passare API/CDN esterni

  e.respondWith(
    fetch(e.request)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy)).catch(() => {});
        return res;
      })
      .catch(() => caches.match(e.request))
  );
});
